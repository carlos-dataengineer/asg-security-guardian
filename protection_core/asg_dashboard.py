def _lang(state: Path) -> str:
    try:
        value = json.loads((state / "config.json").read_text(encoding="utf-8")).get("lang", "pt")
    except Exception:
        value = "pt"
    return value if value in TEXT else "en"


def _tilde(text: str) -> str:
    """Show the home folder (short or long Windows form, any slash) as ~."""
    home = Path.home()
    variants = set()
    forms = [str(home), str(home.resolve())]
    if os.name == "nt":
        try:
            import ctypes
            buf = ctypes.create_unicode_buffer(1024)
            if ctypes.windll.kernel32.GetShortPathNameW(str(home), buf, 1024):
                forms.append(buf.value)
        except Exception:
            pass
    for h in forms:
        variants.update({h, h.replace("\\", "/")})
    for v in sorted(variants, key=len, reverse=True):
        text = re.sub(re.escape(v), "~", text, flags=re.IGNORECASE)
    return text


def _parse_ts(value: str) -> datetime | None:
    try:
        dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
    except Exception:
        return None


def _ago(dt: datetime | None, T: dict) -> str:
    if not dt:
        return T["never"]
    secs = max(0, (datetime.now(timezone.utc) - dt).total_seconds())
    if secs < 60:
        return T["ago_now"]
    if secs < 3600:
        return T["ago_min"].format(n=int(secs // 60))
    if secs < 86400:
        return T["ago_h"].format(n=int(secs // 3600))
    return T["ago_d"].format(n=int(secs // 86400))


# ============================================================================ data
def verdict(report: dict) -> str:
    counts = report.get("counts", {})
    findings = report.get("findings", [])
    if counts.get("INCONCLUSIVE"):
        return "inconclusive"
    if any(f["id"] in STRONG_IDS and f["severity"] in {"CRITICAL", "HIGH"} for f in findings):
        return "review"
    if any(f["severity"] not in {"INFO", "LOW"} for f in findings):
        return "attention"
    return "clean"


def load_reports(state: Path) -> list[dict]:
    out = []
    reports = state / "reports"
    if not reports.exists():
        return out
    files = sorted(reports.glob("asg-*.json"), key=lambda p: p.stat().st_mtime, reverse=True)
    for jp in files[:MAX_SCANS]:
        try:
            r = json.loads(jp.read_text(encoding="utf-8"))
        except Exception:
            continue
        r.pop("inventory", None)  # large and not needed for display
        r["_json"] = str(jp)
        r["_md"] = str(jp.with_suffix(".md"))
        out.append(r)
    return out


def load_events(state: Path) -> list[dict]:
    log = state / "audit.jsonl"
    if not log.exists():
        return []
    events = []
    for raw in log.read_text(encoding="utf-8", errors="replace").splitlines()[-MAX_EVENTS:]:
        try:
            events.append(json.loads(raw))
        except Exception:
            continue
    return list(reversed(events))


def load_quarantine(state: Path) -> list[dict]:
    out = []
    for p in sorted((state / "requests").glob("*.json"), key=lambda x: x.stat().st_mtime, reverse=True) if (state / "requests").exists() else []:
        try:
            out.append(json.loads(p.read_text(encoding="utf-8")))
        except Exception:
            continue
    return out[:200]


def chain_status(state: Path) -> dict | None:
    try:
        spec = importlib.util.spec_from_file_location("asg_local_dash", Path(__file__).with_name("asg_local.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod.verify_audit(state)
    except Exception:
        return None


def protection_status() -> dict:
    """Which ASG shields are registered, per agent, plus core integrity. Read-only."""
    home = Path.home()
    claude = Path(os.environ.get("CLAUDE_CONFIG_DIR", str(home / ".claude"))).expanduser()
    codex = Path(os.environ.get("CODEX_HOME", str(home / ".codex"))).expanduser()

    def hooks_in(path: Path) -> list[str]:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            return []
        found = set()
        for event, groups in (data.get("hooks") or {}).items():
            for g in groups or []:
                for h in g.get("hooks", []) or []:
                    if "asg_hook.py" in str(h.get("command", "")) + str(h.get("commandWindows", "")):
                        found.add(event)
        return sorted(found)

    clients = {}
    if claude.exists():
        clients["claude"] = {"hooks": hooks_in(claude / "settings.json"),
                             "skill": (claude / "skills" / "asg-security-guardian" / "SKILL.md").exists()}
    if codex.exists():
        clients["codex"] = {"hooks": hooks_in(codex / "hooks.json"),
                            "skill": (home / ".agents" / "skills" / "asg-security-guardian" / "SKILL.md").exists()}
    manifest_path = Path(__file__).with_name("manifest.json")
    integrity, version = None, "dev"
    if manifest_path.exists():
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            version = manifest.get("version", "?")
            integrity = all(
                (manifest_path.parent / name).exists()
                and hashlib.sha256((manifest_path.parent / name).read_bytes()).hexdigest() == digest
                for name, digest in manifest.get("files", {}).items())
        except Exception:
            integrity = False
    return {"clients": clients, "integrity": integrity, "version": version}


