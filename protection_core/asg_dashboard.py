def _activity_chart(reports: list[dict], events: list[dict], T: dict) -> str:
    today = datetime.now(timezone.utc).date()
    days = [today - timedelta(days=i) for i in range(13, -1, -1)]
    idx = {d: i for i, d in enumerate(days)}
    data = [[0, 0, 0, 0] for _ in days]  # clean, attention, review, gate
    for r in reports:
        dt = _parse_ts(r.get("created_at", ""))
        if dt and dt.date() in idx:
            v = verdict(r)
            data[idx[dt.date()]][{"clean": 0, "attention": 1}.get(v, 2)] += 1
    for ev in events:
        if ev.get("type") in ("install_gate", "install_ran"):
            dt = _parse_ts(ev.get("timestamp", ""))
            if dt and dt.date() in idx:
                data[idx[dt.date()]][3] += 1
    peak = max([sum(x) for x in data] + [1])
    w, h, pad, bw = 700, 170, 24, 30
    step = (w - 2 * pad) / len(days)
    colors = ["var(--ok)", "var(--med)", "var(--crit)", "var(--accent)"]
    parts = [f"<svg class='chart' viewBox='0 0 {w} {h + 26}' role='img' aria-label='{e(T['activity14'])}'>"]
    for gy in (0.25, 0.5, 0.75, 1):
        y = h - (h - 10) * gy
        parts.append(f"<line x1='{pad}' x2='{w - pad}' y1='{y:.1f}' y2='{y:.1f}' class='grid'/>")
    for i, (d, vals) in enumerate(zip(days, data)):
        x = pad + i * step + (step - bw) / 2
        y = h
        for k, val in enumerate(vals):
            if not val:
                continue
            bh = (h - 10) * val / peak
            y -= bh
            parts.append(f"<rect x='{x:.1f}' y='{y:.1f}' width='{bw}' height='{bh:.1f}' rx='4' fill='{colors[k]}'>"
                         f"<title>{d.isoformat()}: {val}</title></rect>")
        if i % 2 == 1 or i == len(days) - 1:
            parts.append(f"<text x='{x + bw / 2:.1f}' y='{h + 18}' class='axis'>{d.strftime('%d/%m')}</text>")
    parts.append("</svg>")
    legend = "".join(f"<span><i style='background:{c}'></i>{e(T[k])}</span>"
                     for c, k in zip(colors, ("leg_clean", "leg_att", "leg_rev", "leg_block")))
    return "".join(parts) + f"<div class='legend'>{legend}</div>"


def _severity_donut(reports: list[dict], T: dict) -> str:
    c = Counter(f["severity"] for r in reports for f in r.get("findings", []) if f["severity"] != "INFO")
    order = [("CRITICAL", "var(--crit)"), ("HIGH", "var(--high)"), ("MEDIUM", "var(--med)"), ("LOW", "var(--muted)"), ("INCONCLUSIVE", "var(--inc)")]
    total = sum(c[k] for k, _ in order)
    r, circ = 52, 2 * math.pi * 52
    parts = ["<div class='donut'><svg viewBox='0 0 140 140' role='img'>",
             f"<circle cx='70' cy='70' r='{r}' class='track'/>"]
    offset = 0.0
    for k, col in order:
        if not c[k]:
            continue
        seg = circ * c[k] / total
        parts.append(f"<circle cx='70' cy='70' r='{r}' fill='none' stroke='{col}' stroke-width='16' "
                     f"stroke-dasharray='{seg:.2f} {circ - seg:.2f}' stroke-dashoffset='{-offset:.2f}' "
                     f"transform='rotate(-90 70 70)'><title>{k}: {c[k]}</title></circle>")
        offset += seg
    parts.append(f"<text x='70' y='68' class='dn'>{total}</text><text x='70' y='88' class='dl'>{e('achados' if T is TEXT['pt'] else 'findings')}</text></svg><ul>")
    for k, col in order:
        parts.append(f"<li><i style='background:{col}'></i>{k}<b>{c[k]}</b></li>")
    parts.append("</ul></div>")
    return "".join(parts)


def _top_rules(reports: list[dict], T: dict) -> str:
    c = Counter(f["id"] for r in reports for f in r.get("findings", []) if f["severity"] not in ("INFO", "LOW"))
    if not c:
        return f"<p class='muted'>{T['no_data']}</p>"
    top = c.most_common(6)
    peak = top[0][1]
    rows = []
    for rid, n in top:
        cls = "crit" if rid in STRONG_IDS else "med"
        rows.append(f"<div class='rule'><span>{e(rid)}</span><div class='rb'><i class='{cls}' style='width:{max(4, 100 * n / peak):.0f}%'></i></div><b>{n}</b></div>")
    return "".join(rows)


