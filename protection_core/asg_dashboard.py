def _modules(protection: dict | None, chain: dict | None, T: dict) -> list[dict]:
    clients = (protection or {}).get("clients", {})

    def per_event(event):
        return {c: event in info.get("hooks", []) for c, info in clients.items()}

    def state_of(flags: dict):
        if not flags:
            return "off"
        return "on" if all(flags.values()) else ("warn" if any(flags.values()) else "off")

    integ = (protection or {}).get("integrity")
    mods = [
        {"key": "download", "flags": per_event("PostToolUse")},
        {"key": "install", "flags": per_event("PreToolUse")},
        {"key": "ext", "flags": per_event("SessionStart")},
        {"key": "skill", "flags": {c: bool(info.get("skill")) for c, info in clients.items()}},
    ]
    for m in mods:
        m["state"] = state_of(m["flags"])
    mods.append({"key": "integrity", "flags": {}, "state": "dev" if integ is None else ("on" if integ else "off")})
    mods.append({"key": "audit", "flags": {}, "state": "on" if (chain is None or chain.get("valid")) else "off"})
    return mods


