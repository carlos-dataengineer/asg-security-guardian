def _status(reports, verdicts, protection, chain) -> tuple[str, int]:
    week = datetime.now(timezone.utc) - timedelta(days=7)
    pending = sum(1 for r, v in zip(reports, verdicts)
                  if v in ("review", "inconclusive") and (_parse_ts(r.get("created_at", "")) or week) > week)
    if protection is None:
        return ("warn" if pending else "unknown"), pending
    mods = _modules(protection, chain, TEXT["en"])
    shields_off = any(m["state"] == "off" for m in mods if m["key"] in ("download", "install", "integrity", "audit"))
    if not protection.get("clients") or shields_off:
        return "bad", pending
    return ("warn" if pending else "ok"), pending


