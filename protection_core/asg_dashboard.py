def build(state: Path = STATE) -> Path:
    state.mkdir(parents=True, exist_ok=True)
    out = state / "dashboard.html"
    page = render(load_reports(state), _lang(state), load_events(state), chain_status(state),
                  protection_status(), load_quarantine(state), state)
    out.write_text(page, encoding="utf-8")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Build the ASG Security Center dashboard")
    ap.add_argument("--state", default=str(STATE))
    ap.add_argument("--open", action="store_true", help="open in the default browser")
    ap.add_argument("--actions", action="store_true", help="open directly on the Activity view")
    ap.add_argument("--view", choices=["overview", "scans", "threats", "actions", "quarantine", "protection"])
    args = ap.parse_args()
    out = build(Path(args.state).expanduser())
    print(f"Dashboard: {out}")
    view = "actions" if args.actions else args.view
    if args.open or view:
        webbrowser.open(out.as_uri() + (f"#{view}" if view else ""))
    return 0


